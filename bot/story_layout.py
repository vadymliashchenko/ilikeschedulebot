# Прив'язка кожного шаблону сторіс до конкретної години й дня-патерну.
# "rows" - порядок хореографів зверху вниз САМЕ так, як їх намальовано в шаблоні
# (це порядок дизайну, він не обов'язково збігається з порядком у config.SCHEDULE).

# Більшість шаблонів оновлено дизайнером до 1080x1920 (справжня якість Instagram
# Stories); "ср" (wed_only) тимчасово лишається старим 720x1280, поки немає нового.
# Межі пігулки в обох випадках виміряно напряму з пікселів шаблону - вони НЕ
# пропорційні одне одному (новий дизайн має інші відносні відступи), тому для
# кожної роздільної здатності - свій окремий, реально виміряний набір.
_PILL_BOUNDS_BY_WIDTH = {
    720: {
        "y_bounds": [
            (355, 429),
            (522, 596),
            (700, 774),
            (868, 941),
            (1049, 1122),
        ],
        "x": (520, 718),  # пігулка йде до краю канви
        "scale": 1.0,  # базова роздільна здатність - усі розміри шрифтів/іконок звідси
    },
    1080: {
        "y_bounds": [
            (539, 636),
            (790, 886),
            (1056, 1153),
            (1307, 1404),
            (1579, 1676),
        ],
        "x": (776, 1078),  # пігулка йде до краю канви
        "scale": 1.315,  # висота пігулки зросла не пропорційно ширині канви (~97px проти ~74px)
    },
}


def pill_bounds(image_width: int) -> dict:
    try:
        return _PILL_BOUNDS_BY_WIDTH[image_width]
    except KeyError:
        supported = sorted(_PILL_BOUNDS_BY_WIDTH)
        raise ValueError(
            f"Немає виміряних меж пігулки для ширини {image_width}px - підтримуються лише "
            f"{supported}. Якщо додано новий шаблон іншого розміру, потрібно виміряти й додати "
            f"новий запис у _PILL_BOUNDS_BY_WIDTH."
        ) from None

