# перевірки. Межі задані ПОСЛОТОВО (за (day_pattern, time)), а не по ширині
# картинки, як у старому дизайні - при однаковій ширині 1275px різні файли не
# є пікселі-в-піксель однаковими. x/scale однакові для всіх, бо порожня зона
# праворуч (де раніше була пігулка) і масштаб тексту в дизайні не змінюються
