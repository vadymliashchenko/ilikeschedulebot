# Прив'язка кожного шаблону сторіс до конкретної години й дня-патерну.
# "rows" - порядок хореографів зверху вниз САМЕ так, як їх намальовано в шаблоні
# (це порядок дизайну, він не обов'язково збігається з порядком у config.SCHEDULE).

# "ср" (wed_only) лишається старим шаблоном 720x1280 (наразі середа все одно
# закрита - групу не проводимо, тож цей запис не генерується жодного дня).
_PILL_BOUNDS_BY_WIDTH = {
    720: {
        "y_bounds": [
            (355, 429),
            (522, 596),
            (700, 774),
            (868, 941),
            (1049, 1122),
        ],
        "x": (520, 718),  # пігулка йде до краю канви
        "scale": 1.0,  # базова роздільна здатність - усі розміри шрифтів/іконок звідси
    },
}


def pill_bounds(image_width: int) -> dict:
    try:
        return _PILL_BOUNDS_BY_WIDTH[image_width]
    except KeyError:
        supported = sorted(_PILL_BOUNDS_BY_WIDTH)
        raise ValueError(
            f"Немає виміряних меж пігулки для ширини {image_width}px - підтримуються лише "
            f"{supported}. Якщо додано новий шаблон іншого розміру, потрібно виміряти й додати "
            f"новий запис у _PILL_BOUNDS_BY_WIDTH (або, якщо кожен файл цієї серії має трохи "
            f"інше розташування рядків, окремий запис у _SLOT_BOUNDS)."
        ) from None


# Новий дизайн шаблонів (2026-09-09, 1275x2268) - на відміну від старих 720/1080,
# тут немає рамки під пігулку взагалі (статус просто малюється поверх фону
# праворуч), і що важливіше - розташування рядків трохи "плаває" від файлу до
# файлу. y_bounds - це РЕАЛЬНІ верх/низ кольорової смуги кожного рядка (не
# позиція тексту імені) - заміряно по кожному з 8 файлів окремо: спершу
# автоматично (пошук фото хореографа через локальну дисперсію пікселів у
# колонці x=20..220 - фото "шумне", фон/смуга "гладкі"), потім кожен результат
# звірено з оригіналом дизайнерською перевіркою (лінії-межі накладені на
# картинку й переглянуті) - для tue_fri 20:00 (рядки 2 і 3 злилися в одну
# зону через низьку контрастність одягу) і mon_thu 17:00 (нижня межа рядка 3
# відсікала текст "(6-9 РОКІВ)") межі відкориговано вручну за результатами
# перевірки. Межі задані ПОСЛОТОВО (за (day_pattern, time)), а не по ширині
# картинки, як у старому дизайні - при однаковій ширині 1275px різні файли не
# є пікселі-в-піксель однаковими. x/scale однакові для всіх, бо порожня зона
# праворуч (де раніше була пігулка) і масштаб тексту в дизайні не змінюються
# від файлу до файлу.
#
# СТАТУС ЦЕНТРУЄТЬСЯ РІВНО ПО ЦЕНТРУ ПОВНОЇ КОЛЬОРОВОЇ СМУГИ (однакова
# відстань до верхнього і нижнього краю - явна вимога користувача 2026-09-10,
# перевірено на прикладі tue_fri 17:00, який користувач назвав еталонним).
#
# ІСТОРІЯ ПОМИЛКИ (щоб не повторити знову): 2026-09-10 користувач показав
# шаблон зі стрілками дизайнера навколо кожного статусу, і ці стрілки були
# ЗНАЧНО вужчими за повну смугу (~150-165px, а не ~300px) - звідси зробили
# ХИБНИЙ висновок, що y_bounds має бути цією вузькою зоною (формула
# name_top-20/+165). Насправді ЦЕНТР вузької стрілочної зони майже ідеально
# збігається з ЦЕНТРОМ повної смуги (напр. tue_fri17 рядок1: стрілки
# (487,651)→центр 569; повна смуга (405,713)→центр 559 - різниця 10px) -
# стрілки показували, де опиняється КОРОТКИЙ текст після центрування в
# ПОВНІЙ смузі, а не окрему "безпечну зону". Використання вузької зони як
# `box_h` для центрування давало систематично неправильний результат на
# файлах, де текст імені хореографа розташований не по центру своєї смуги
# (тому в одних рядках статус "гуляв" ближче до верху, в інших - до низу
# смуги - саме на це поскаржився користувач). Правильно - завжди рахувати
# центр від РЕАЛЬНИХ верх/низ смуги (photo-variance метод, п.2 вище).
