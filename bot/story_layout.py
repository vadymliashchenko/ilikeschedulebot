# Прив'язка кожного шаблону сторіс до конкретної години й дня-патерну.
# "rows" - порядок хореографів зверху вниз САМЕ так, як їх намальовано в шаблоні
# (це порядок дизайну, він не обов'язково збігається з порядком у config.SCHEDULE).

# "ср" (wed_only) лишається старим шаблоном 720x1280 (наразі середа все одно
# закрита - групу не проводимо, тож цей запис не генерується жодного дня).
_PILL_BOUNDS_BY_WIDTH = {
    720: {
        "y_bounds": [
            (355, 429),
            (522, 596),
            (700, 774),
            (868, 941),
            (1049, 1122),
        ],
        "x": (520, 718),  # пігулка йде до краю канви
        "scale": 1.0,  # базова роздільна здатність - усі розміри шрифтів/іконок звідси
    },
}


def pill_bounds(image_width: int) -> dict:
    try:
        return _PILL_BOUNDS_BY_WIDTH[image_width]
    except KeyError:
        supported = sorted(_PILL_BOUNDS_BY_WIDTH)
        raise ValueError(
            f"Немає виміряних меж пігулки для ширини {image_width}px - підтримуються лише "
            f"{supported}. Якщо додано новий шаблон іншого розміру, потрібно виміряти й додати "
            f"новий запис у _PILL_BOUNDS_BY_WIDTH (або, якщо кожен файл цієї серії має трохи "
            f"інше розташування рядків, окремий запис у _SLOT_BOUNDS)."
        ) from None


# Новий дизайн шаблонів (2026-09-09, 1275x2268) - на відміну від старих 720/1080,
# тут немає рамки під пігулку взагалі (статус просто малюється поверх фону
# праворуч), і що важливіше - розташування рядків трохи "плаває" від файлу до
# файлу. y_bounds - це РЕАЛЬНІ верх/низ кольорової смуги кожного рядка (не
# позиція тексту імені) - заміряно по кожному з 8 файлів окремо: спершу
# автоматично (пошук фото хореографа через локальну дисперсію пікселів у
# колонці x=20..220 - фото "шумне", фон/смуга "гладкі"), потім кожен результат
# звірено з оригіналом дизайнерською перевіркою (лінії-межі накладені на
# картинку й переглянуті) - для tue_fri 20:00 (рядки 2 і 3 злилися в одну
# зону через низьку контрастність одягу) і mon_thu 17:00 (нижня межа рядка 3
