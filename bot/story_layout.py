# праворуч), і що важливіше - розташування рядків трохи "плаває" від файлу до
# файлу. y_bounds - це РЕАЛЬНІ верх/низ кольорової смуги кожного рядка (не
# позиція тексту імені) - заміряно по кожному з 8 файлів окремо: спершу
# автоматично (пошук фото хореографа через локальну дисперсію пікселів у
